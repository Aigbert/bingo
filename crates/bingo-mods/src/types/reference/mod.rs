//! `.bingo/reference.md`: every event, `$` method, element and site this
//! build has, generated from the same schemas and tables the types are.
use bingo_sdk::Catalog;
use serde_json::Value;
mod dollar;
mod events;
mod sites;

const HEAD: &str = "# bingo mod reference\n\nGenerated by `bingo plugins types` from this build; do not edit. The same text is JSDoc in `.bingo/types/`. Types named here are declared there (`grep -rn 'export type Name' .bingo/types/`).\n\n";

pub(super) fn reference(events: &Catalog) -> String {
    let mut text = String::from(HEAD);
    text.push_str(&events::section(events));
    text.push_str(&dollar::section());
    text.push_str(&sites::elements());
    text.push_str(&sites::components());
    text
}

/// The top-level fields of `schema`, one line each, or its type when it is
/// not an object. References resolve against `root`.
fn fields(root: &Value, schema: &Value) -> String {
    let resolved = resolve(root, schema);
    let Some(properties) = resolved["properties"].as_object() else {
        return format!("`{}`\n", short(schema));
    };
    let required: Vec<&str> = resolved["required"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .collect();
    let mut text = String::new();
    for (name, field) in properties {
        let optional = if required.contains(&name.as_str()) {
            ""
        } else {
            "?"
        };
        let kind = bingo_schema_ts::expression(field, 0);
        text.push_str(&format!("- `{name}{optional}`: `{kind}`"));
        if let Some(doc) = field["description"].as_str() {
            text.push_str(&format!(" — {}", one_line(doc)));
        }
        text.push('\n');
    }
    if properties.is_empty() {
        text.push_str("- no fields\n");
    }
    text
}

/// A type short enough for one line: a union as wide as `View` reads as
/// its name, which the laid types declare.
fn short(schema: &Value) -> String {
    let expression = bingo_schema_ts::expression(schema, 0);
    match schema["title"].as_str() {
        Some(title) if expression.len() > 160 || expression.contains('\n') => title.into(),
        _ => expression,
    }
}

fn resolve<'a>(root: &'a Value, schema: &'a Value) -> &'a Value {
    schema["$ref"]
        .as_str()
        .and_then(|reference| root.pointer(reference.trim_start_matches('#')))
        .unwrap_or(schema)
}

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

